CREATE DATABASE IF NOT EXISTS textrpg CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER IF NOT EXISTS 'textrpg'@'localhost' IDENTIFIED BY 'change-me';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE ON textrpg.* TO 'textrpg'@'localhost';
FLUSH PRIVILEGES;

USE textrpg;
CREATE TABLE IF NOT EXISTS save_slots (
    slot_id TINYINT UNSIGNED NOT NULL,
    player_name VARCHAR(40) NOT NULL,
    level SMALLINT UNSIGNED NOT NULL,
    location VARCHAR(80) NOT NULL,
    state_json JSON NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (slot_id),
    CONSTRAINT chk_save_slot_id CHECK (slot_id BETWEEN 1 AND 3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
